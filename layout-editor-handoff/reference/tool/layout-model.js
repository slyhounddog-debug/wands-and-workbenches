// Layout tab: the data model shared by the tool's server (layout.mjs), the tab UI (layout.js) and the
// in-iframe editor (layout-host.js). No DOM, no Node APIs, so all three can import it.
//
//   { version: 1, rules: [ { sel: "#start-planks", css: { translate: "12px -4px", width: "300px" }, text: { "0": "New Game" } } ] }
//
//   sel   a CSS selector (may match one element or many)
//   css   raw declarations, written to css/layout.css as `sel { prop: value !important; }`
//   text  { childNodeIndex: string } replaces that direct text node of every matched element; applied by
//         js/LayoutOverrides.js at game start (text cannot be done in CSS)

export const MODEL_VERSION = 1;
export const emptyModel = () => ({ version: MODEL_VERSION, rules: [] });

const SEL_BAD = /[{};<@]|\/\*|\*\//;
const VAL_BAD = /[{};<@\\]|\/\*|\*\/|url\s*\(|expression\s*\(|!\s*important/i;

export const isSafeSelector = (s) => typeof s === 'string' && s.length > 0 && s.length <= 400 && !SEL_BAD.test(s);
export const isSafeProp = (p) => typeof p === 'string' && /^-?[a-z][a-z0-9-]{0,60}$/.test(p);
export const isSafeValue = (v) => typeof v === 'string' && v.length > 0 && v.length <= 300 && !VAL_BAD.test(v);

// Returns a cleaned copy of whatever was sent (dropping anything unsafe or empty) so a bad edit can never
// put junk in css/layout.css; throws on a structurally wrong document.
export function sanitizeModel(input) {
  if (!input || typeof input !== 'object' || !Array.isArray(input.rules)) throw new Error('not a layout model');
  const rules = [];
  const seen = new Set();
  for (const r of input.rules) {
    if (!r || !isSafeSelector(r.sel) || seen.has(r.sel)) continue;
    const css = {};
    for (const [p, v] of Object.entries(r.css || {})) if (isSafeProp(p) && isSafeValue(String(v))) css[p] = String(v).trim();
    const text = {};
    for (const [k, v] of Object.entries(r.text || {})) if (/^\d{1,4}$/.test(k) && typeof v === 'string' && v.length <= 2000) text[k] = v;
    if (!Object.keys(css).length && !Object.keys(text).length) continue;
    seen.add(r.sel);
    const out = { sel: r.sel };
    if (Object.keys(css).length) out.css = css;
    if (Object.keys(text).length) out.text = text;
    rules.push(out);
  }
  return { version: MODEL_VERSION, rules };
}

// The stylesheet the game links (css/layout.css). The editor injects the same string as a live <style>.
export function modelToCss(model) {
  const out = [];
  for (const r of model.rules) {
    const decls = Object.entries(r.css || {}).map(([p, v]) => `  ${p}: ${v} !important;`);
    if (decls.length) out.push(`${r.sel} {\n${decls.join('\n')}\n}`);
  }
  return out.join('\n\n');
}

