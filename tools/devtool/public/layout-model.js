// Layout tab: the data model shared by the server (server.mjs), the tab (layout.js) and the in-preview editor
// (layout-host.js). A classic script that sets globalThis.LayoutModel, because the preview loads it before any game
// script runs and the game itself has no modules.
//
//   { version: 1, rules: [ { sel: "#quest", css: { translate: "12px -4px", width: "300px" }, text: { "0": "Goal" } } ] }
//
//   sel   a CSS selector (may match one element or many)
//   css   raw declarations, written to overrides/layout.css as `sel { prop: value !important; }`
//   text  { childNodeIndex: string } replaces that direct text node of every matched element (js/overrides.js)
(function () {
  const MODEL_VERSION = 1;
  const SEL_BAD = /[{};<@]|\/\*|\*\//;
  const VAL_BAD = /[{};<@\\]|\/\*|\*\/|url\s*\(|expression\s*\(|!\s*important/i;
  const isSafeSelector = s => typeof s === 'string' && s.length > 0 && s.length <= 400 && !SEL_BAD.test(s);
  const isSafeProp = p => typeof p === 'string' && /^-?[a-z][a-z0-9-]{0,60}$/.test(p);
  const isSafeValue = v => typeof v === 'string' && v.length > 0 && v.length <= 300 && !VAL_BAD.test(v);

  // a cleaned copy of whatever was sent (unsafe or empty bits dropped); throws on a structurally wrong document
  function sanitizeModel(input) {
    if (!input || typeof input !== 'object' || !Array.isArray(input.rules)) throw new Error('not a layout model');
    const rules = [], seen = new Set();
    for (const r of input.rules) {
      if (!r || !isSafeSelector(r.sel) || seen.has(r.sel)) continue;
      const css = {};
      for (const [p, v] of Object.entries(r.css || {})) if (isSafeProp(p) && isSafeValue(String(v))) css[p] = String(v).trim();
      const text = {};
      for (const [k, v] of Object.entries(r.text || {})) if (/^\d{1,4}$/.test(k) && typeof v === 'string' && v.length <= 2000) text[k] = v;
      if (!Object.keys(css).length && !Object.keys(text).length) continue;
      seen.add(r.sel);
      const out = { sel: r.sel };
      if (Object.keys(css).length) out.css = css;
      if (Object.keys(text).length) out.text = text;
      rules.push(out);
    }
    return { version: MODEL_VERSION, rules };
  }

  // the stylesheet the game links (overrides/layout.css); the preview injects the same string as a live <style>
  function modelToCss(model) {
    const out = [];
    for (const r of model.rules) {
      const decls = Object.entries(r.css || {}).map(([p, v]) => '  ' + p + ': ' + v + ' !important;');
      if (decls.length) out.push(r.sel + ' {\n' + decls.join('\n') + '\n}');
    }
    return out.join('\n\n');
  }

  globalThis.LayoutModel = {
    MODEL_VERSION, sanitizeModel, modelToCss, isSafeSelector,
    emptyModel: () => ({ version: MODEL_VERSION, rules: [] }),
    CSS_HEADER: '/* GENERATED by the dev tool\'s Layout tab (tools/devtool) from overrides/layout.json: edit there, not here. Linked last in index.html. */\n',
  };
})();
